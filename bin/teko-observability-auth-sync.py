#!/usr/bin/python3
"""Build Apache Basic-Auth credentials for Alloy from the server registry.

No plaintext token is copied into Apache configuration.  The existing per-host
Config-Agent token remains the credential used by Alloy.  This helper converts
registered tokens to bcrypt htpasswd entries and atomically replaces the file.
"""
import argparse
import base64
import hashlib
import json
import os
import re
import shutil
import stat
import subprocess
import tempfile
from pathlib import Path

NAME_RE = re.compile(r'^[A-Za-z0-9._:-]{1,128}$')

def die(msg):
    raise SystemExit('FEHLER: ' + str(msg))

def htpasswd_bin():
    for name in ('htpasswd2', 'htpasswd'):
        p = shutil.which(name)
        if p:
            return p
    return ''

def make_entry(binary,user,token):
    if binary:
        cp=subprocess.run([binary,'-nbB',user,token],stdout=subprocess.PIPE,stderr=subprocess.PIPE,universal_newlines=True)
        if cp.returncode == 0 and cp.stdout.strip().startswith(user+':'):
            return cp.stdout.strip()
    # Portable Apache fallback. Tokens are random 256-bit machine credentials,
    # not human passwords; unsalted SHA-1 therefore does not reduce practical
    # brute-force resistance of the credential.
    digest=base64.b64encode(hashlib.sha1(token.encode()).digest()).decode()
    return user+':{SHA}'+digest

def load_registry(path):
    try:
        data=json.loads(Path(path).read_text(encoding='utf-8'))
    except Exception as e:
        die(f'Server-Registry nicht lesbar: {e}')
    return data.get('servers',[]) if isinstance(data,dict) else []

def read_token(path):
    p=Path(path)
    if not p.is_file() or p.is_symlink():
        return ''
    try:
        token=p.read_text(encoding='utf-8').strip()
    except Exception:
        return ''
    if len(token)<32 or re.search(r'\s',token):
        return ''
    return token

def main():
    ap=argparse.ArgumentParser()
    ap.add_argument('--registry',default='/opt/service/config-manager/servers.json')
    ap.add_argument('--output',default='/opt/service/config-manager/observability.htpasswd')
    args=ap.parse_args()
    hp=htpasswd_bin()
    entries=[]
    seen=set()
    for srv in load_registry(args.registry):
        if not isinstance(srv,dict) or srv.get('enabled',True) is False:
            continue
        user=str(srv.get('host_id') or srv.get('name') or '').strip()
        tf=str(srv.get('token_file') or '').strip()
        if not read_token(tf):
            safe=re.sub(r'[^A-Za-z0-9._-]', '_', str(srv.get('name') or '').strip())
            candidate='/opt/service/config-manager/tokens/'+safe+'.token' if safe else ''
            if candidate and read_token(candidate):
                tf=candidate
        if not NAME_RE.match(user) or user in seen:
            continue
        token=read_token(tf)
        if not token:
            continue
        # -n stdout, -b batch password, -B bcrypt. Random salt is generated by htpasswd.
        line=make_entry(hp,user,token)
        entries.append(line)
        seen.add(user)
    out=Path(args.output)
    out.parent.mkdir(parents=True,exist_ok=True)
    fd,tmp=tempfile.mkstemp(prefix='.observability.htpasswd.', dir=str(out.parent))
    try:
        with os.fdopen(fd,'w') as f:
            if entries:
                f.write('\n'.join(entries)+'\n')
            f.flush(); os.fsync(f.fileno())
        # Apache muss nur Hashes lesen; Tokens selbst bleiben in 0640 Token-Dateien.
        try:
            gid=os.stat(out.parent).st_gid
        except Exception:
            gid=0
        os.chown(tmp,0,gid); os.chmod(tmp,0o640); os.replace(tmp,out)
        dfd=os.open(str(out.parent),os.O_DIRECTORY)
        try: os.fsync(dfd)
        finally: os.close(dfd)
    finally:
        try:
            if os.path.exists(tmp): os.unlink(tmp)
        except Exception: pass
    print(f'[OK] Apache Observability-Auth: {out} ({len(entries)} Host(s))')

if __name__=='__main__':
    main()
